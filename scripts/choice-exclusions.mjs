// Re-derives the exception list `src/core/choiceitems.ts` is built on: which status moves
// Showdown's team generator will pair with a Choice item.
//
// The law that file states — a Choice item and a status move never share a random-battle
// set — is not a mechanic anyone can read off the sim. It is a property of how
// `data/random-battles/*/teams.ts` assembles sets, which is a thousand lines of interacting
// special cases, so the only honest way to know it is to generate sets and look. This is
// that measurement, kept in the tree so the claim stays falsifiable rather than becoming
// folklore about a generator that has since moved on.
//
// LOCAL, needs the `.ps-server` checkout (cloned on first use, as `player-check` does).
// Deliberately NOT part of `npm run check`: it needs a checkout CI has no reason to carry,
// and a few minutes to say anything trustworthy. Run it when Showdown's generator changes,
// or when a deduction looks wrong in a real battle.
//
//   npm run choice-exclusions              # every published feed, 8k teams each
//   node scripts/choice-exclusions.mjs 30000
//
// It prints the list and exits non-zero when it disagrees with the one in the source, so a
// disagreement is a failure you can see rather than a paragraph someone has to re-read.

import {readFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {ensureLocalCheckout} from './lib/local-server.mjs';

// Every format `pkmn.github.io/randbats` publishes a set feed for — the exact list the
// extension can ever load, so the exact list the law has to hold across.
const FORMATS = [
  'gen9randombattle', 'gen9randomdoublesbattle', 'gen9babyrandombattle',
  'gen9championsrandombattle', 'gen9championsrandomdoublesbattle',
  'gen8randombattle', 'gen8bdsprandombattle',
  'gen7randombattle', 'gen7letsgorandombattle',
  'gen6randombattle', 'gen5randombattle', 'gen4randombattle',
  'gen3randombattle', 'gen2randombattle', 'gen1randombattle',
];

const CHOICE = new Set(['choiceband', 'choicespecs', 'choicescarf']);
const toId = (s) => String(s).toLowerCase().replace(/[^a-z0-9]+/g, '');

/** The list as `choiceitems.ts` currently has it, read from the source so the two cannot
 *  drift apart silently — a check that compares a file against itself checks nothing. */
function declaredExceptions() {
  const src = readFileSync(fileURLToPath(new URL('../src/core/choiceitems.ts', import.meta.url)), 'utf8');
  const block = /const PAIRS_WITH_CHOICE: ReadonlySet<string> = new Set\(\[([^\]]*)\]\)/s.exec(src);
  if (!block) throw new Error('could not find PAIRS_WITH_CHOICE in src/core/choiceitems.ts');
  return new Set([...block[1].matchAll(/'([a-z0-9]+)'/g)].map((m) => m[1]));
}

async function main() {
  const teamsPerFormat = Number(process.argv[2] || 8000);
  const simPath = ensureLocalCheckout();
  const {Teams, Dex} = (await import(simPath)).default ?? (await import(simPath));

  const stat = new Map(); // move id → {name, total, choice, example}
  let sets = 0;
  let choiceSets = 0;
  for (const format of FORMATS) {
    const gen = Number(/gen(\d)/.exec(format)?.[1] ?? 9);
    const dex = Dex.forGen(gen);
    try {
      Teams.generate(format);
    } catch {
      console.log(`  ${format}: not generated by this checkout — skipped`);
      continue;
    }
    for (let i = 0; i < teamsPerFormat; i++) {
      for (const set of Teams.generate(format)) {
        sets++;
        const choice = CHOICE.has(toId(set.item || ''));
        if (choice) choiceSets++;
        for (const move of set.moves) {
          const id = toId(move);
          // The category is read per GEN: a move can be a status move in one and an attack
          // in another, and the feed for each gen is generated by that gen's own dex.
          if (dex.moves.get(id)?.category !== 'Status') continue;
          const row = stat.get(id) ?? {name: move, total: 0, choice: 0, example: ''};
          row.total++;
          if (choice) {
            row.choice++;
            row.example ||= `${format} ${set.species} ${set.item}`;
          }
          stat.set(id, row);
        }
      }
    }
    process.stdout.write(`  ${format}: ${sets} sets so far\n`);
  }

  const measured = [...stat.entries()].filter(([, r]) => r.choice > 0).sort((a, b) => b[1].choice - a[1].choice);
  console.log(`\n${sets.toLocaleString()} sets, ${choiceSets.toLocaleString()} holding a Choice item, ` +
    `${stat.size} distinct status moves seen.\n`);
  console.log('Status moves that appeared beside a Choice item:');
  for (const [id, r] of measured) {
    console.log(`  ${r.name.padEnd(14)} ${String(r.choice).padStart(7)} of ${String(r.total).padStart(7)} ` +
      `(${((r.choice / r.total) * 100).toFixed(1)}%)  e.g. ${r.example}  [${id}]`);
  }

  const declared = declaredExceptions();
  const found = new Set(measured.map(([id]) => id));
  const missing = [...found].filter((id) => !declared.has(id));
  const unseen = [...declared].filter((id) => !found.has(id));

  // The two disagreements are NOT symmetric, which is the whole point of reporting them
  // apart. A move measured beside a Choice item and absent from the source is a live bug:
  // the deduction is ruling out an item that set really can hold. A declared move this run
  // never saw is only a rarity the sample missed — dropping it would trade a harmless
  // over-caution for a possible lie, so it is reported and nothing more.
  if (unseen.length > 0) {
    console.log(`\nDeclared but not seen this run (keep them — a bigger sample is how they showed up): ${unseen.join(', ')}`);
  }
  if (missing.length > 0) {
    console.error(`\nFAIL: ${missing.join(', ')} appeared beside a Choice item and are NOT in ` +
      "PAIRS_WITH_CHOICE. Every set holding one is being told it cannot hold the item it holds. " +
      'Add them to src/core/choiceitems.ts, with this run\'s numbers in the docblock.');
    process.exitCode = 1;
    return;
  }
  console.log('\nOK: the source\'s exception list covers everything this run measured.');
}

await main();
