// Re-derives the exception list `src/core/restitem.ts` is built on: which abilities let a
// Rest-without-Sleep-Talk set escape being forced onto Chesto Berry.
//
// The law itself — `moves.has('rest') && !moves.has('sleeptalk') && ability !== 'Natural
// Cure' && ability !== 'Shed Skin'` forces Chesto Berry — is one branch of gen9's
// `getPriorityItem`, quoted in `restitem.ts`'s own header. Reading it is not proof any more
// than it was for `choiceitems.ts` next door: the two OTHER things that skip this branch (an
// evolution-stage override, Giratina's own species carve-out) are hand-carved special cases
// a source read can miss, which is exactly why `restitem.ts` doesn't hardcode them — it
// instead requires Chesto Berry to already be a live possibility in the role's own item
// pool, so this script's job is to confirm THAT strategy actually accounts for every
// non-ability exception it finds, not just to recite the two ability names.
//
// Scoped to the gen9-family formats, because only they carry the per-role feed shape (and
// the exact branch above) this law reads — an older generation either lacks the branch
// entirely (gen1-3) or hand-carves its OWN extra exceptions (gen4's Shuckle, gen6/7's
// Hydration) that gen9 does not share, and `restitem.ts` never runs against a role-less
// entry in the first place.
//
// LOCAL, needs the `.ps-server` checkout (cloned on first use, as `player-check` does).
// Deliberately NOT part of `npm run check`: it needs a checkout CI has no reason to carry,
// and a couple of minutes to say anything trustworthy. Run it when Showdown's generator
// changes, or when a Rest-holding set's item looks wrong in a real battle.
//
//   npm run rest-item-exclusions              # every gen9-family format, 6k teams each
//   node scripts/rest-item-exclusions.mjs 20000

import {readFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {ensureLocalCheckout} from './lib/local-server.mjs';

// The gen9-family formats this law is actually MEASURED against. Every generation but
// gen1 and Let's Go carries the same per-role feed shape (see `types.ts`'s
// `RandbatsEntry`), but that shape is not this law: gen2/gen3 have no Chesto-Berry branch
// at all, and gen4 (Shuckle) and gen6/7 (Hydration) hand-carve their own extra exceptions
// this file's `RECOVERY_EXCUSES` does not enumerate. Sampling those generations here would
// just report their DIFFERENT law as a failure of this one.
const FORMATS = [
  'gen9randombattle', 'gen9randomdoublesbattle', 'gen9babyrandombattle',
  'gen9championsrandombattle', 'gen9championsrandomdoublesbattle',
];

const toId = (s) => String(s || '').toLowerCase().replace(/[^a-z0-9]+/g, '');

/** The ability exception set as `restitem.ts` currently has it, read from the source so the
 *  two cannot drift apart silently — a check that compares a file against itself checks
 *  nothing. */
function declaredExcuses() {
  const src = readFileSync(fileURLToPath(new URL('../src/core/restitem.ts', import.meta.url)), 'utf8');
  const block = /const RECOVERY_EXCUSES: ReadonlySet<string> = new Set\(\[([^\]]*)\]\)/s.exec(src);
  if (!block) throw new Error('could not find RECOVERY_EXCUSES in src/core/restitem.ts');
  return new Set([...block[1].matchAll(/'([a-z0-9]+)'/g)].map((m) => m[1]));
}

async function main() {
  const teamsPerFormat = Number(process.argv[2] || 6000);
  const simPath = ensureLocalCheckout();
  const {Teams, Dex} = (await import(simPath)).default ?? (await import(simPath));
  const declared = declaredExcuses();

  let restNoTalk = 0;
  const abilityOutcomes = new Map(); // ability id → {name, total, chesto}
  const unexplained = []; // non-Chesto, non-NFE, non-Giratina, ability not yet declared

  for (const format of FORMATS) {
    const gen = Number(/gen(\d)/.exec(format)?.[1] ?? 9);
    const dex = Dex.forGen(gen);
    let generated = 0;
    try {
      Teams.generate(format);
    } catch (e) {
      console.log(`  ${format}: not generated by this checkout — skipped (${e.message})`);
      continue;
    }
    for (let i = 0; i < teamsPerFormat; i++) {
      for (const set of Teams.generate(format)) {
        const moveIds = set.moves.map(toId);
        if (!moveIds.includes('rest') || moveIds.includes('sleeptalk')) continue;
        restNoTalk++;

        const itemId = toId(set.item);
        const chesto = itemId === 'chestoberry';
        const abilityId = toId(set.ability);
        const row = abilityOutcomes.get(abilityId) ?? {name: set.ability, total: 0, chesto: 0};
        row.total++;
        if (chesto) row.chesto++;
        abilityOutcomes.set(abilityId, row);

        if (chesto || declared.has(abilityId)) continue;
        const species = dex.species.get(set.species);
        if (species.nfe || species.id === 'giratina') continue;
        unexplained.push({format, species: set.species, ability: set.ability, item: set.item});
      }
      generated++;
    }
    process.stdout.write(`  ${format}: ${generated} teams, ${restNoTalk} rest-no-talk so far\n`);
  }

  console.log(`\n${restNoTalk} sets with Rest and no Sleep Talk, across ${FORMATS.length} formats.\n`);
  console.log('Ability outcomes for those sets:');
  for (const [id, r] of [...abilityOutcomes.entries()].sort((a, b) => b[1].total - a[1].total)) {
    const pct = ((r.chesto / r.total) * 100).toFixed(1);
    console.log(`  ${r.name.padEnd(16)} Chesto Berry ${String(r.chesto).padStart(6)} of ${String(r.total).padStart(6)} (${pct}%)  [${id}]`);
  }

  console.log(`\n${unexplained.length} sets got a non-Chesto item without an NFE species, Giratina, ` +
    'or a declared ability excuse:');
  const grouped = new Map();
  for (const u of unexplained) {
    const key = `${u.format} | ${u.species} | ${u.ability} | ${u.item}`;
    grouped.set(key, (grouped.get(key) ?? 0) + 1);
  }
  for (const [key, n] of [...grouped.entries()].sort((a, b) => b[1] - a[1])) {
    console.log(`  ${String(n).padStart(5)}  ${key}`);
  }

  // Informational only: an ability that never once produced Chesto Berry here but isn't
  // declared could be a real gap, OR it could be one this run only ever saw on an NFE
  // species or Giratina (already excused by species, not ability) — `unexplained` above is
  // the one check that judges each set with full context, so it is the only thing that fails
  // the run.
  const undeclaredZero = [...abilityOutcomes.entries()]
    .filter(([id, r]) => r.chesto === 0 && r.total > 0 && !declared.has(id))
    .map(([id]) => id);
  if (undeclaredZero.length > 0) {
    console.log(`\nAbilities that never produced Chesto Berry here and aren't declared (check the sets above ` +
      `before assuming a gap): ${undeclaredZero.join(', ')}`);
  }

  if (unexplained.length > 0) {
    console.error('\nFAIL: the sets above are neither NFE, Giratina, nor an excused ability — restitem.ts\'s ' +
      'exception strategy no longer explains everything this run measured.');
    process.exitCode = 1;
    return;
  }
  console.log('\nOK: every non-Chesto Rest-without-Sleep-Talk set is explained by NFE, Giratina, or a declared ability.');
}

await main();
